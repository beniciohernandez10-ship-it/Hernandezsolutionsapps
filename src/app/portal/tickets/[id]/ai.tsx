"use client";
import { useState, useTransition } from "react";
import { useRouter } from "next/navigation";
import { apiFetch, ApiError } from "@/components/client-api";
import { CATEGORY_LABEL, PRIORITY_LABEL, type Category, type Priority } from "@/lib/tickets/schemas";
import { IconAlert } from "@/components/icons";

interface Suggestion {
  summary: string;
  category: Category;
  priority: Priority;
  nextSteps: string[];
}

/** Technicians: an AI summary with suggested classification. Nothing changes until "Use priority" is pressed. */
export function AiTriageCard({ ticketId, version, priority, category }: { ticketId: string; version: number; priority: string; category: string }) {
  const router = useRouter();
  const [, start] = useTransition();
  const [s, setS] = useState<Suggestion | null>(null);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);

  async function run(fn: () => Promise<void>) {
    setBusy(true);
    setError(null);
    try {
      await fn();
    } catch (e) {
      setError(e instanceof ApiError ? e.message : "Something went wrong.");
    } finally {
      setBusy(false);
    }
  }

  return (
    <section className="card tight stack" aria-labelledby="ai-h">
      <div className="spread">
        <h2 id="ai-h" className="eyebrow">AI assistant · technicians only</h2>
      </div>
      {!s && <p className="subtle">Summarize this request and suggest a category, priority and next steps.</p>}
      {s && (
        <div className="stack ai-output" aria-live="polite">
          <p className="prewrap">{s.summary}</p>
          <dl className="kv">
            <dt>Category</dt>
            <dd>
              {CATEGORY_LABEL[s.category]}
              {s.category === category && <span className="subtle"> (current)</span>}
            </dd>
            <dt>Priority</dt>
            <dd>
              {PRIORITY_LABEL[s.priority]}
              {s.priority === priority && <span className="subtle"> (current)</span>}
            </dd>
          </dl>
          {s.nextSteps.length > 0 && (
            <>
              <strong className="label">Next steps</strong>
              <ol className="ai-steps">
                {s.nextSteps.map((n, i) => (
                  <li key={i}>{n}</li>
                ))}
              </ol>
            </>
          )}
          <p className="subtle">Generated by AI. Check it before acting on it.</p>
        </div>
      )}
      {error && (
        <div className="alert alert-danger" role="alert">
          <IconAlert />
          <div>{error}</div>
        </div>
      )}
      <div className="row">
        <button
          className="btn"
          type="button"
          disabled={busy}
          onClick={() => run(async () => setS(await apiFetch<Suggestion>(`/api/tickets/${ticketId}/ai/triage`, { method: "POST" })))}
        >
          {busy && <span className="spinner" aria-hidden />}
          {s ? "Ask again" : "Summarize and suggest"}
        </button>
        {s && s.priority !== priority && (
          <button
            className="btn"
            type="button"
            disabled={busy}
            onClick={() =>
              run(async () => {
                await apiFetch(`/api/tickets/${ticketId}`, { method: "PATCH", body: { expectedVersion: version, priority: s.priority } });
                start(() => router.refresh());
              })
            }
          >
            Use priority {PRIORITY_LABEL[s.priority]}
          </button>
        )}
      </div>
    </section>
  );
}
